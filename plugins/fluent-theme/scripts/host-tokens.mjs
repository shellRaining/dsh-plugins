// Regenerate src/host/tokens.ts: every --dsw-* custom property the host
// defines, read from the theme and primitives packages in devDependencies.
// Keep those two versions equal to the DSH release in use, and rerun after
// upgrading DSH; `pnpm run build` then reports tokens that no longer exist.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const SOURCES = ['@deepseek-ai/dsh-client-ui-theme', '@deepseek-ai/dsh-client-ui-primitives'];
const DEFINITION = /(--dsw-[a-z0-9-]+)\s*:/g;
const require = createRequire(import.meta.url);

const names = new Set();
const origins = [];
for (const source of SOURCES) {
  const manifest = require.resolve(`${source}/package.json`);
  const { version } = JSON.parse(await readFile(manifest, 'utf8'));
  origins.push(`${source}@${version}`);
  const lib = join(dirname(manifest), 'lib');
  for (const entry of await readdir(lib, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !/\.(?:js|css)$/.test(entry.name)) continue;
    const text = await readFile(join(entry.parentPath ?? entry.path, entry.name), 'utf8');
    for (const [, name] of text.matchAll(DEFINITION)) names.add(name);
  }
}
if (!names.size) throw new Error('No --dsw-* definitions found; check the devDependency packages');

const lines = [...names].sort().map(name => `  | '${name}'`);
const output = `// Generated by \`pnpm run host-tokens\` from ${origins.join(' and ')}.
// Do not edit; rerun after upgrading DSH.
export type HostToken =
${lines.join('\n')};
`;
const target = new URL('../src/host/tokens.ts', import.meta.url);
await writeFile(target, output);
console.log(`Wrote ${names.size} host tokens to src/host/tokens.ts`);
