// Build both halves with esbuild after `tsc` has type-checked them.
// - lib/index.js: host half, one ESM file for Node (no runtime dependencies).
// - lib/client.js: client half, one ModuleLoader registration. The CommonJS
//   bundle runs inside `factory(require)`; react, react/jsx-runtime and the
//   shell primitives stay external and resolve from the shell's seed table.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const CLIENT_EXTERNAL = ['react', 'react/jsx-runtime', '@deepseek-ai/dsh-client-ui-primitives'];
const banner = '// Generated by `pnpm run build`; edit src/, not this file.';

await build({
  entryPoints: [new URL('src/host/index.ts', root).pathname],
  outfile: new URL('lib/index.js', root).pathname,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  banner: { js: banner },
  logLevel: 'warning',
});

const client = await build({
  entryPoints: [new URL('src/client/index.tsx', root).pathname],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: CLIENT_EXTERNAL,
  logLevel: 'warning',
});
const body = client.outputFiles[0].text;
const wrapped = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`;
await writeFile(new URL('lib/client.js', root), wrapped);
console.log(`Built lib/index.js and lib/client.js (${Buffer.byteLength(wrapped)} bytes)`);
