import { randomUUID } from 'node:crypto';
import { mkdir, readFile, realpath, rename, writeFile } from 'node:fs/promises';
import { isBuiltin } from 'node:module';
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

interface Entry {
  entry: string;
  output: string;
  target?: string;
}

interface ClientEntry extends Entry {
  external?: string[];
  /** false 用于源码已经注册 ModuleLoader 的客户端。 */
  wrapped?: boolean;
}

interface HostEntry extends Entry {
  external?: string[] | 'packages';
}

export interface PluginBuildOptions {
  root: URL;
  client?: ClientEntry;
  host?: HostEntry;
}

const banner = '// Generated by `pnpm run build`; edit src/, not this file.\n';

function within(root: string, path: string): boolean {
  const child = relative(root, path);
  return child !== '' && child !== '..' && !child.startsWith(`..${sep}`) && !isAbsolute(child);
}

function packagePath(root: string, path: string): string {
  if (isAbsolute(path) || path.split(/[\\/]/).some(part => !part || part === '.' || part === '..')) {
    throw new Error(`Invalid package path: ${path}`);
  }
  const absolute = resolve(root, path);
  if (!within(root, absolute)) throw new Error(`Path escapes plugin root: ${path}`);
  return absolute;
}

async function buildEntry(root: string, entry: ClientEntry | HostEntry, client: boolean, name: string): Promise<void> {
  const input = packagePath(root, entry.entry);
  const target = packagePath(root, entry.output);
  if (!entry.entry.startsWith('src/') || !within(root, await realpath(input))) {
    throw new Error(`Entry must be inside the plugin src/: ${entry.entry}`);
  }
  // 根目录只有明确命名的 JS 产物可写；其余产物必须在 lib/，不能覆盖 src/。
  if (!/^(?:lib\/)?[\w.-]+\.js$/.test(entry.output) || target === input) {
    throw new Error(`Invalid JavaScript output: ${entry.output}`);
  }
  const directory = dirname(target);
  if (directory !== root) {
    await mkdir(directory, { recursive: true });
    if (!within(root, await realpath(directory))) throw new Error(`Output directory escapes plugin root: ${directory}`);
  }
  const external = entry.external;
  const result = await build({
    root,
    configFile: false,
    envDir: false,
    publicDir: false,
    mode: 'production',
    logLevel: 'warn',
    // library 模式不替换 NODE_ENV；浏览器不能依赖 Node 的 process 全局。
    define: client ? { 'process.env.NODE_ENV': JSON.stringify('production') } : {},
    oxc: { jsx: { runtime: 'automatic' } },
    ssr: { noExternal: true },
    build: {
      lib: {
        entry: input,
        name: 'DSHClientPlugin',
        formats: [client ? ((entry as ClientEntry).wrapped === false ? 'iife' : 'cjs') : 'es'],
        fileName: () => basename(target),
      },
      ssr: !client,
      target: entry.target ?? (client ? 'es2022' : 'node20'),
      // Vite 只生成内存产物，不以插件根目录作为潜在清理目标。
      outDir: join(root, '.vite-output'),
      write: false,
      emptyOutDir: false,
      copyPublicDir: false,
      minify: false,
      sourcemap: false,
      reportCompressedSize: false,
      rolldownOptions: {
        platform: client ? 'browser' : 'node',
        external: id => {
          if (!client && isBuiltin(id)) return true;
          if (!client && external === 'packages') return !id.startsWith('.') && !isAbsolute(id) && !id.startsWith('\0');
          // React 的所有子路径都来自宿主，绝不内联另一份运行时。
          if (client && /^(?:react|react-dom)(?:\/|$)/.test(id)) return true;
          return Array.isArray(external) && external.some(pkg => id === pkg || id.startsWith(`${pkg}/`));
        },
        output: {
          codeSplitting: false,
          exports: client && (entry as ClientEntry).wrapped === false ? 'none' : 'named',
        },
      },
    },
  });
  const bundle = Array.isArray(result) && result.length === 1 ? result[0] : result;
  if (!bundle || !('output' in bundle)) throw new Error('Expected one Vite library build');
  const [chunk] = bundle.output;
  if (bundle.output.length !== 1 || !chunk || chunk.type !== 'chunk' || !chunk.isEntry) {
    throw new Error(`Expected one JavaScript output for ${entry.entry}; separate chunks/assets are not supported`);
  }
  let text = banner + chunk.code;
  if (client && (entry as ClientEntry).wrapped !== false) {
    text = `${banner}window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${chunk.code}
    return module.exports;
  },
});
`;
  }
  const temporary = `${target}.${process.pid}.${randomUUID()}.tmp`;
  // 原子替换前同时核对最终文件和临时文件的绝对路径。
  if (!within(root, target) || !within(root, temporary) || dirname(temporary) !== directory) {
    throw new Error('Invalid atomic output path');
  }
  await writeFile(temporary, text, { flag: 'wx' });
  await rename(temporary, target);
  console.log(`Built ${name}: ${entry.output} (${Buffer.byteLength(text)} bytes)`);
}

export async function buildPlugin({ root, client, host }: PluginBuildOptions): Promise<void> {
  if (root.protocol !== 'file:' || !root.pathname.endsWith('/')) throw new Error('Plugin root must be a directory file URL');
  const directory = await realpath(fileURLToPath(root));
  const pkg: unknown = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  if (!pkg || typeof pkg !== 'object' || !('name' in pkg) || typeof pkg.name !== 'string') {
    throw new Error('Plugin package.json must declare its name');
  }
  if (host) await buildEntry(directory, host, false, pkg.name);
  if (client) await buildEntry(directory, client, true, pkg.name);
}
